# Maps labels from the keymap grid to special instructions for ZMK and QMK.
# "LABEL": ("ZMK", "QMK")
SPECIAL_LABELS = {
    # Bluetooth
    "BT_CLR": ("&bt BT_CLR", "KC_NO"),
    "BT_0": ("&bt BT_SEL 0", "KC_NO"),
    "BT_1": ("&bt BT_SEL 1", "KC_NO"),
    "BT_2": ("&bt BT_SEL 2", "KC_NO"),
    "BT_3": ("&bt BT_SEL 3", "KC_NO"),
}

# Maps labels from the keymap grid to layer numbers.
LAYER_LABELS = {
    "RSE": 1,
    "LWR": 2,
    "HYP": 3,
    "ADJ": 4,
    "MOU": 5,
}

# Hold-tap flavors a key may ask for, matching the suffix of the behaviors in
# `zmk_template.dtsi`. Keys default to 'tap preferred', which suits the
# home-row; the thumb keys ask for 'hold preferred'. Sticky keys have a single
# behavior and take no flavor.
FLAVORS = ("tp", "hp")
DEFAULT_FLAVOR = "tp"


################################################################################
# Mapping to QMK


def get_qmk_key_press_code(label):
    if label.startswith('CMD_'):
        return f"G({get_qmk_key_press_code(label[4:])})"
    elif label.startswith('HYP_'):
        return f"G(S(A(C({get_qmk_key_press_code(label[4:])}))))"
    elif len(label) == 1 and (label.isalpha() or label.isdigit()):
        return f"KC_{label}"
    elif label in KEY_PRESS_CODES:
        return KEY_PRESS_CODES[label][1]
    return None


def map_key_label_to_qmk(label):
    code = get_qmk_key_press_code(label)
    if code:
        return code
    elif label in LAYER_LABELS:
        return f"MO({LAYER_LABELS[label]})"
    elif label in SPECIAL_LABELS:
        return SPECIAL_LABELS[label][1]
    elif not label:
        return "KC_NO"
    raise KeyError(f"Cannot map label {label} to qmk.")


def map_key_to_qmk(key):
    if not key.hold:
        return map_key_label_to_qmk(key.tap)
    if not key.tap:
        return map_key_label_to_qmk(key.hold)

    # QMK has no per key hold-tap flavors, so they are ignored here. One shot
    # keycodes are the closest match for sticky keys: they stick on tap and act
    # as a plain modifier or layer shift when held.
    if key.hold in LAYER_LABELS:
        if key.is_sticky:
            return f"OSL({LAYER_LABELS[key.hold]})"
        tap_code = get_qmk_key_press_code(key.tap)
        if tap_code:
            return f"LT({LAYER_LABELS[key.hold]},{tap_code})"
    else:
        hold_code = get_qmk_key_press_code(key.hold)
        if hold_code:
            hold_code = hold_code.replace("KC_", "MOD_")
            if key.is_sticky:
                return f"OSM({hold_code})"
            tap_code = get_qmk_key_press_code(key.tap)
            if tap_code:
                return f"MT({hold_code},{tap_code})"
    raise KeyError(f"Cannot map hold-tap key ({key.tap}, {key.hold}) to qmk.")


def generate_qmk_combo(combo):
    if not combo:
        return ('KC_NO', 'KC_NO')
    return (", ".join((map_key_label_to_qmk(combo.a), map_key_label_to_qmk(combo.b))), map_key_label_to_qmk(combo.result))


def generate_qmk_layer(layer):
    return ",\n".join(
        ", ".join(map_key_to_qmk(key) for key in row) for row in layer.rows
    )


