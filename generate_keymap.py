# Mapping to ZMK


def get_zmk_key_press_code(label):
    label = normalize_label(label)
    if not label:
        return None
    key = lookup_key(label)
    if key.startswith("CMD_"):
        return f"LG({get_zmk_key_press_code(_suffix_after_prefix(label, key, 'CMD_'))})"
    if key.startswith("HYP_"):
        return (
            f"LA(LS(LC(LG({get_zmk_key_press_code(_suffix_after_prefix(label, key, 'HYP_'))}))))"
        )
    if label.isalpha() and len(label) == 1:
        return label.upper()
    if label.isdigit() and len(label) == 1:
        return f"N{label}"
    if key in KEY_PRESS_CODES:
        return KEY_PRESS_CODES[key][0]
    if label in KEY_PRESS_CODES:
        return KEY_PRESS_CODES[label][0]
    return None


def map_key_label_to_zmk(label):
    code = get_zmk_key_press_code(label)
    if code:
        return f"&kp {code}"
    key = lookup_key(label)
    if key in LAYER_LABELS:
        return f"&mo {LAYER_LABELS[key]}"
    if key in SPECIAL_LABELS:
        return SPECIAL_LABELS[key][0]
    if not normalize_label(label):
        return "&trans"
    raise KeyError(f"Cannot map label {label!r} to zmk.")


def map_tap_hold_key_to_zmk(tap, hold):
    if not hold:
        return map_key_label_to_zmk(tap)
    if not tap:
        return map_key_label_to_zmk(hold)

    tap_code = get_zmk_key_press_code(tap)
    hold_code = get_zmk_key_press_code(hold)
    hold_key = lookup_key(hold)
    if tap_code:
        if hold_code:
            return f"&mt_ {hold_code} {tap_code}"
        if hold_key in LAYER_LABELS:
            return f"&lt_ {LAYER_LABELS[hold_key]} {tap_code}"
    raise KeyError(f"Cannot map thumb key ({tap}, {hold}) to zmk.")


