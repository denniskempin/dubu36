def generate_zmk_layer(layer):
    rows = []
    for row in layer.rows[:3]:
        # Pad to Corne 6-column firmware while authoring a 5-column layout.
        rows.append(
            "&trans "
            + " ".join(map_tap_hold_key_to_zmk(tap, hold) for tap, hold in row)
            + " &trans"
        )
    rows.append(
        " ".join(map_tap_hold_key_to_zmk(tap, hold) for tap, hold in layer.rows[3])
    )
    return "\n".join(rows)


################################################################################
# keymap-drawer YAML parsing


def parse_key_spec(spec):
    """Convert a keymap-drawer LayoutKey (str or mapping) to TapHold."""
    if spec is None:
        return TapHold("", None)
    if isinstance(spec, str):
        return TapHold(spec, None)
    if isinstance(spec, dict):
        tap = normalize_label(spec.get("t", spec.get("tap", spec.get("center", ""))))
        hold = normalize_label(
            spec.get("h", spec.get("hold", spec.get("bottom", "")))
        )
        return TapHold(tap, hold or None)
    raise TypeError(f"Unsupported key spec: {spec!r}")


def flatten_layer_keys(layer_value):
    """Flatten row-grouped keymap-drawer layer lists into a flat key list."""
    keys = []

    def walk(node):
        if isinstance(node, list):
            for item in node:
                walk(item)
        else:
            keys.append(node)

    walk(layer_value)
    return keys


def rows_from_flat_keys(flat_keys, columns=5, thumbs=3):
    """Split a flat 36-key list into 3x10 + thumb row of 6."""
    expected = columns * 2 * 3 + thumbs * 2
    if len(flat_keys) != expected:
        raise ValueError(
            f"Expected {expected} keys for {columns}x3+{thumbs} split, got {len(flat_keys)}"
        )
    rows = []
    idx = 0
    for _ in range(3):
        rows.append([parse_key_spec(k) for k in flat_keys[idx : idx + columns * 2]])
        idx += columns * 2
    rows.append([parse_key_spec(k) for k in flat_keys[idx : idx + thumbs * 2]])
    return rows


def parse_combos(combos_data, layer_names):
    """Best-effort combo parse; unused today but keeps schema room to grow."""
    combos = []
    for combo in combos_data or []:
        key = combo.get("k", combo.get("key", ""))
        if isinstance(key, dict):
            key = key.get("t", key.get("tap", ""))
        triggers = combo.get("tk", combo.get("trigger_keys"))
        if triggers and len(triggers) >= 2:
            a = triggers[0] if isinstance(triggers[0], str) else triggers[0].get("t", "")
            b = triggers[1] if isinstance(triggers[1], str) else triggers[1].get("t", "")
            combos.append(Combo(normalize_label(a), normalize_label(b), normalize_label(key)))
    return combos


def load_layers(keymap_path):
    with open(keymap_path, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f)

    layout = data.get("layout", {}).get("ortho_layout", {})
    columns = int(layout.get("columns", 5))
    thumbs = int(layout.get("thumbs", 3))

    layers = []
    for name, value in (data.get("layers") or {}).items():
        flat = flatten_layer_keys(value)
        rows = rows_from_flat_keys(flat, columns=columns, thumbs=thumbs)
        layers.append(Layer(name=name, rows=rows, combos=[]))

    # Attach top-level combos to the first layer for the existing template slots.
    if layers:
        layers[0] = layers[0]._replace(
            combos=parse_combos(data.get("combos"), [l.name for l in layers])
        )
    return layers


################################################################################
# Generate Keymaps


def generate_keymap(layers, template_path, generate_layer_fn, generate_combo_fn):
    with open(template_path, "r", encoding="utf-8") as template_file:
        template = template_file.read()
        combos = []
        for i, layer in enumerate(layers):
            template = template.replace(f"#LAYER_{i}#", generate_layer_fn(layer))
            combos.extend(layer.combos)
        for combo_id in range(5):
            trigger, result = generate_combo_fn(
                combos[combo_id] if combo_id < len(combos) else None
            )
            template = template.replace(f"#COMBO_TRIGGER_{combo_id}#", trigger)
            template = template.replace(f"#COMBO_RESULT_{combo_id}#", result)
        return HEADER + template


def usage():
    print(f"Usage: {sys.argv[0]} qmk|zmk")


def main(type_: str):
    root_dir = os.path.dirname(os.path.abspath(__file__))
    layers = load_layers(os.path.join(root_dir, "keymap.yaml"))
    if type_ == "zmk":
        print(
            generate_keymap(
                layers,
                os.path.join(root_dir, "zmk_template.dtsi"),
                generate_zmk_layer,
                generate_zmk_combo,
            )
        )
    elif type_ == "qmk":
        print(
            generate_keymap(
                layers,
                os.path.join(root_dir, "qmk_template.c"),
                generate_qmk_layer,
                generate_qmk_combo,
            )
        )
    else:
        usage()


if __name__ == "__main__":
    if len(sys.argv) > 1:
        main(sys.argv[1])
    else:
        usage()
