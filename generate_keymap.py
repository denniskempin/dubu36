# Generate Keymaps


def generate_keymap(layers, combos, template_path, generate_layer_fn, generate_combo_fn):
    with open(template_path, "r") as template_file:
        template = template_file.read()
        for i, layer in enumerate(layers):
            template = template.replace(f"#LAYER_{i}#", generate_layer_fn(layer))
        for combo_id in range(5):
            (trigger, result) = generate_combo_fn(
                combos[combo_id] if combo_id < len(combos) else None)
            template = template.replace(f"#COMBO_TRIGGER_{combo_id}#", trigger)
            template = template.replace(f"#COMBO_RESULT_{combo_id}#", result)
        return HEADER + template


def usage():
    print(f"Usage: {sys.argv[0]} qmk|zmk")


def main(type: str):
    root_dir = os.path.dirname(__file__)
    layers, combos = parse_keymap(os.path.join(root_dir, "keymap.txt"))
    if type == "zmk":
        print(
            generate_keymap(
                layers,
                combos,
                os.path.join(root_dir, "zmk_template.dtsi"),
                generate_zmk_layer,
                generate_zmk_combo,
            )
        )
    elif type == "qmk":
        print(
            generate_keymap(
                layers,
                combos,
                os.path.join(root_dir, "qmk_template.c"),
                generate_qmk_layer,
                generate_qmk_combo,
            )
        )
    else:
        usage()


if len(sys.argv) > 1:
    main(sys.argv[1])
else:
    usage()
