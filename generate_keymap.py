TapHold = namedtuple("TapHold", ("tap", "hold"))
Combo = namedtuple("Combo", ("a", "b", "result"))
Layer = namedtuple("Layer", ("name", "rows", "combos"))


def normalize_label(label):
    if label is None:
        return ""
    return str(label).strip()


def lookup_key(label):
    """Return uppercase lookup key for maps; preserve single-char symbols."""
    label = normalize_label(label)
    if not label:
        return ""
    if len(label) == 1:
        return label.upper() if label.isalpha() else label
    return label.upper().replace("-", "_")


