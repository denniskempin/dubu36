# Mapping to QMK


def _suffix_after_prefix(label, key, prefix):
    """Return the label portion after a CMD_/HYP_-style prefix."""
    if "_" in label:
        return label.split("_", 1)[1]
    return key[len(prefix) :]


def get_qmk_key_press_code(label):
    label = normalize_label(label)
    if not label:
        return None
    key = lookup_key(label)
    if key.startswith("CMD_"):
        return f"G({get_qmk_key_press_code(_suffix_after_prefix(label, key, 'CMD_'))})"
    if key.startswith("HYP_"):
        return (
            f"G(S(A(C({get_qmk_key_press_code(_suffix_after_prefix(label, key, 'HYP_'))}))))"
        )
    if len(label) == 1 and (label.isalpha() or label.isdigit()):
        return f"KC_{label.upper()}"
    if key in KEY_PRESS_CODES:
        return KEY_PRESS_CODES[key][1]
    if label in KEY_PRESS_CODES:
        return KEY_PRESS_CODES[label][1]
    return None


def map_key_label_to_qmk(label):
    code = get_qmk_key_press_code(label)
    if code:
        return code
    key = lookup_key(label)
    if key in LAYER_LABELS:
        return f"MO({LAYER_LABELS[key]})"
    if key in SPECIAL_LABELS:
        return SPECIAL_LABELS[key][1]
    if not normalize_label(label):
        return "KC_NO"
    raise KeyError(f"Cannot map label {label!r} to qmk.")


def map_tap_hold_key_to_qmk(tap, hold):
    if not hold:
        return map_key_label_to_qmk(tap)
    if not tap:
        return map_key_label_to_qmk(hold)

    tap_code = get_qmk_key_press_code(tap)
    hold_code = get_qmk_key_press_code(hold)
    hold_key = lookup_key(hold)
    if tap_code:
        if hold_code:
            hold_code = hold_code.replace("KC_", "MOD_")
            return f"MT({hold_code},{tap_code})"
        if hold_key in LAYER_LABELS:
            return f"LT({LAYER_LABELS[hold_key]},{tap_code})"
    raise KeyError(f"Cannot map thumb key ({tap}, {hold}) to qmk.")


def generate_qmk_combo(combo):
    if not combo:
        return ("KC_NO", "KC_NO")
    return (
        ", ".join((map_key_label_to_qmk(combo.a), map_key_label_to_qmk(combo.b))),
        map_key_label_to_qmk(combo.result),
    )


def generate_qmk_layer(layer):
    rows = []
    for row in layer.rows:
        rows.append(
            ", ".join(map_tap_hold_key_to_qmk(tap, hold) for tap, hold in row)
        )
    return ",\n".join(rows)


